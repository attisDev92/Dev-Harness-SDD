// Antigravity adapter (RF-ADP-01/02/06). Antigravity reads AGENTS.md on its
// own and loads skills on demand, so besides the skills, the workflows and the
// hooks it gets one always-on rule with the parts of the flow Gemini models
// tend to drop: the brief for every subagent, real verification and the scope.
//
//   .agents/rules/sdd-harness.md       always-on rule (≤ 12 000 characters)
//   .agents/skills/<name>/SKILL.md     copies of the canonical skills + one role-* skill per role
//   .agents/workflows/sdd-<cmd>.md     the /sdd:* flow commands
//   .agents/hooks.json                 the guards, with Antigravity's tool names

import { neededRoles } from '../context.js';
import { withMdHeader, quoteFrontmatter } from '../core.js';
import { roleText, commands } from './claude-code.js';

export const id = 'antigravity';
export const RULES = ['commits', 'deps', 'protected', 'docs', 'verify', 'lanes'];

const S = 'node .harness/scripts/sdd.js';

function workflowFile(description, body) {
  return quoteFrontmatter(`---
description: ${description}
---
<!-- Generated by sdd-harness. Do not edit by hand: run "sdd-harness sync". -->

${body}
`);
}

function roleSkillFile(role, text, writes = []) {
  return quoteFrontmatter(`---
name: role-${role}
description: "${text.description}"
---
<!-- Generated by sdd-harness. Do not edit by hand: run "sdd-harness sync". -->

# Role: ${role}

${text.body}

You may write only in: ${writes.length ? writes.map((w) => `\`${w}\``).join(', ') : 'nothing (read-only role)'}.
Do not commit or push directly. Follow AGENTS.md. Keep your final report concise.
`);
}

/**
 * The always-on rule: short, in the language of the runtime messages, with
 * only what the model must never improvise. Everything else stays in the skills.
 */
export function rulesFile(config) {
  const interview = (config.gates?.decisions ?? 'summary') === 'interview';
  return `---
trigger: always_on
---
<!-- Generated by sdd-harness. Do not edit by hand: run "sdd-harness sync". -->

# sdd-harness: flujo obligatorio

Este proyecto sigue Spec-Driven Development con sdd-harness. AGENTS.md tiene las reglas completas; la skill \`sdd\` dirige el flujo. Cárgala antes de cualquier trabajo de código y cada vez que el usuario pida una funcionalidad, un cambio o seguir con el trabajo.

- **Estado y órdenes**: \`${S} status\` dice dónde estamos. El estado vive en \`specs/*/spec.md\` (\`status\`) y en las casillas de \`tasks.md\`; no lo deduzcas de memoria.
- **Dos paradas** (spec y plan): pide la aprobación al usuario y, cuando diga que sí, regístrala con \`${S} approve\`. Nada se implementa sin el plan aprobado.
- **Delegar**: \`${S} next\` lista las tareas listas (hasta el máximo de subagentes a la vez de cada desarrollador, que ahí mismo se indica). Para cada una ejecuta \`${S} brief <TID>\` y pásale al subagente (invoke_subagent, Role = el rol que indica el brief) **ese brief tal cual** como instrucciones: lleva el alcance, los requisitos y las reglas. Nunca más subagentes a la vez de los que indica \`next\` (cada desarrollador fija el suyo con \`${S} agents <1-4>\`).
- **Verificación real**: una tarea solo se cierra con \`${S} verify --component <id> --tests\` en verde y después \`${S} done <TID>\`, que lo comprueba y rechaza si no. Nunca marques \`tasks.md\` a mano ni des por ejecutados tests que no ejecutaste; no inventes resultados.
- **Solo el alcance de la tarea**: nada de refactors, limpieza, cambios de estilo ni de UI fuera de ella. Si hacen falta, añádelos a \`tasks.md\` como "añadida en implementación" y sigue.
- **Decisiones pendientes** (aclaraciones, ADRs en borrador, tareas añadidas, avisos): \`${S} decisions\` las lista. ${interview ? 'En este proyecto se entrevista al usuario sobre ellas, una pregunta cada vez, antes de seguir.' : 'En este proyecto se registran y se cuentan en el resumen; el usuario pide la entrevista con /sdd:decisions.'}
- **Pausa**: si el usuario quiere parar o retomar luego, \`${S} pause\`; termina lo activo, no lances nada nuevo y da un resumen de cómo retomar (\`${S} resume\`).
- **Nunca**: editar \`.harness/\` ni archivos generados; push, rebase o reset sin que lo pidan; terminar con la verificación en rojo sin decirlo.
`;
}

const hook = (event) => ({ type: 'command', command: `node .harness/scripts/hook.js ${event}` });

export function generate(config, ctx) {
  const entries = [];
  const notices = [];
  const add = (e) => entries.push({ generator: id, tool: id, ...e });

  add({ kind: 'file', path: '.agents/rules/sdd-harness.md', content: rulesFile(config) });

  for (const [name, content] of Object.entries(ctx.skills ?? {})) {
    add({ kind: 'file', path: `.agents/skills/${name}/SKILL.md`, content: withMdHeader(content) });
  }

  // Role skills, so Antigravity subagents (which have no agent definition file) get the role's guidelines.
  const texts = roleText();
  for (const { role, writes } of neededRoles(config)) {
    const text = texts[role];
    if (text) {
      add({ kind: 'file', path: `.agents/skills/role-${role}/SKILL.md`, content: roleSkillFile(role, text, writes) });
    }
  }

  // The same shortcuts as Claude Code, with Antigravity's delegation tool. Arguments arrive in the conversation.
  const workflows = commands(config, { delegate: 'delegate', subagentNote: ' using invoke_subagent (Role = the role name, e.g. backend-dev, and load the skill role-<role>)' });
  for (const [name, [description, , body]] of Object.entries(workflows)) {
    add({ kind: 'file', path: `.agents/workflows/sdd-${name}.md`, content: workflowFile(description, body.replace(/\s*\$ARGUMENTS/g, name === 'spec' ? ' what the user describes (ask for a short description if they gave none)' : '')) });
  }

  add({
    kind: 'json',
    path: '.agents/hooks.json',
    values: {},
    appends: {
      'sdd-guards.PreToolUse': [
        { matcher: 'run_command|write_to_file|replace_file_content|invoke_subagent', hooks: [hook('PreToolUse')] }
      ],
      'sdd-guards.PostToolUse': [
        { matcher: 'write_to_file|replace_file_content|invoke_subagent', hooks: [hook('PostToolUse')] }
      ],
      'sdd-guards.PreInvocation': [
        { hooks: [hook('PreInvocation')] }
      ],
      'sdd-guards.UserPromptSubmit': [
        { hooks: [hook('UserPromptSubmit')] }
      ],
      'sdd-guards.SessionStart': [
        { hooks: [hook('SessionStart')] }
      ],
      'sdd-guards.Stop': [
        { hooks: [hook('Stop')] }
      ]
    },
    enforces: RULES
  });

  return { entries, notices };
}
