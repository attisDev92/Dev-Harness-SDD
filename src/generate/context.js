/** RF-GEN-03: context of one component. */
export function componentContext(config, id) {
  const c = config.components[id];
  const lang = config.language?.docs ?? 'en';
  const t = contextStrings(lang);
  const hints = STACK_HINTS[lang] ?? STACK_HINTS.en;
  const parts = String(c.stack ?? '').toLowerCase().split(/[+\s,]+/);
  const verify = ['lint', 'typecheck', 'test', 'e2e'].filter((k) => c.verify?.[k]);
  return [
    `<!-- ${t.note} -->`,
    `# ${t.compTitle(id)}`,
    '',
    `- ${t.compStack(c.stack)}`,
    `- ${t.compOwner(implementerFor(c.kind ?? 'other'))}`,
    ...(c.id_prefix ? [`- ${t.compPrefix(c.id_prefix)}`] : []),
    '',
    t.compVerify,
    '',
    ...(verify.length ? verify.map((k) => `- ${k}: \`${c.verify[k]}\``) : [`- ${t.notConfigured}`]),
    ...(parts.some((p) => hints[p]) ? ['', ...parts.filter((p) => hints[p]).map((p) => `- ${hints[p]}`)] : []),
  ].join('\n');
}
