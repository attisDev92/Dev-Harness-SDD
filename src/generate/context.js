export function contextStrings(lang) {
  return L[lang] ?? L.en;
}

function verifyCell(v, t) {
  const cmds = ['lint', 'typecheck', 'test', 'e2e'].filter((k) => v?.[k]).map((k) => `${k}: \`${v[k]}\``);
  return cmds.length ? cmds.join('<br>') : t.notConfigured;
}

/**
 * @param {object} config
 * @param {{ componentFiles: Record<string, string | null> }} ctx  where each
 *   component's context lives (null when it is covered by the root file)
 */
export function rootContext(config, ctx) {
  const lang = config.language?.docs ?? 'en';
  const t = contextStrings(lang);
  const whitelist = config.docs_whitelist ?? [...DEFAULT_DOCS_WHITELIST];
  const protectedZones = Object.entries(config.protected ?? {}).filter(([, globs]) => globs?.length);
  const comps = Object.entries(config.components ?? {});
  const out = [
    `<!-- ${t.note} -->`,
    `# ${t.title}`,
    '',
    `## ${t.precedence}`,
    '',
    t.precedenceText(config.conventions?.sources ?? []),
    '',
    `## ${t.workflow}`,
    '',
    t.workflowText,
    '',
    t.commands,
    '',
    `## ${t.rules}`,
    '',
    `- ${t.ruleCommit}`,
    `- ${t.ruleDeps}`,
    `- ${t.ruleProtected}`,
    ...protectedZones.map(([name, globs]) => `  - ${name}: ${globs.map((g) => `\`${g}\``).join(', ')}`),
    `- ${t.ruleRetries(config.retries?.in_scope ?? 2)}`,
    `- ${t.ruleVerify}`,
    `- ${t.ruleManual(config.gates?.manual_test ?? 'task')}`,
    `- ${t.ruleDocs} ${whitelist.map((w) => `\`${w}\``).join(', ')}.`,
    `- ${t.ruleLanes}`,
    `- ${t.ruleHarness}`,
    '',
    `## ${t.components}`,
    '',
    t.compHeader,
    '|---|---|---|---|---|---|',
    ...comps.map(([id, c]) => `| \`${id}\` | \`${c.path}\` | ${c.stack ?? ''} | ${c.id_prefix ?? ''} | \`${implementerFor(c.kind ?? 'other')}\` | ${verifyCell(c.verify, t)} |`),
    '',
    ...comps.flatMap(([id, c]) => {
      const file = ctx.componentFiles?.[id];
      if (!file) return [];
      return [t.readBefore(file, c.path)];
    }),
    `## ${t.roles}`,
    '',
    ...neededRoles(config).map(({ role, writes }) => `- \`${role}\`: ${writes.length ? writes.map((w) => `\`${w}\``).join(', ') : t.readOnly}`),
    '',
    `## ${t.conventions}`,
    '',
    `- ${t.languages(config.language ?? {})}`,
    `- ${t.commitStyle(config.conventions?.commits, config.conventions?.commits_note)}`,
    ...(config.conventions?.style?.length ? [`- ${t.style(config.conventions.style)}`] : []),
  ];
  // Keep a blank line between the component pointers and the next heading.
  return out.join('\n').replace(/\n(## )/g, '\n\n$1').replace(/\n{3,}/g, '\n\n');
}

