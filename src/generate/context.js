import { DEFAULT_DOCS_WHITELIST } from '../guards/project.js';

export const ALWAYS_ROLES = ['spec-reviewer', 'architect', 'qa-tester', 'reviewer', 'debugger', 'doc-writer'];

/** Implementer role for a component kind. `other` (CLI, library…) is non-UI code. */
export function implementerFor(kind) {
  return kind === 'frontend' ? 'frontend-dev' : 'backend-dev';
}

const joinPath = (base, glob) => (base === '.' || base === '' ? glob : `${base.replace(/\/$/, '')}/${glob}`);

/** The architect writes specs and ADRs, in every repository that owns specs (RF-TOP-02). */
function architectWrites(config) {
  const out = ['specs/**', 'docs/decisions/**'];
  if (['multi-repo', 'workspace'].includes(config.topology)) {
    for (const c of Object.values(config.components ?? {})) {
      const dir = String(c.path).replace(/\\/g, '/').replace(/^\.\/?/, '').replace(/\/$/, '');
      if (dir) out.push(`${dir}/specs/**`, `${dir}/docs/decisions/**`);
    }
  }
  return [...new Set(out)];
}

/**
 * RF-GEN-04 / RF-DOM-01: only the roles the project needs, with the paths
 * each one may write.
 */
export function neededRoles(config) {
  const comps = Object.entries(config.components ?? {});
  const writes = new Map();
  for (const [, c] of comps) {
    const role = implementerFor(c.kind ?? 'other');
    if (!writes.has(role)) writes.set(role, []);
    writes.get(role).push(joinPath(c.path, '**'));
  }
  const whitelist = config.docs_whitelist ?? [...DEFAULT_DOCS_WHITELIST];
  const tests = comps.flatMap(([, c]) => [joinPath(c.path, 'tests/**'), joinPath(c.path, 'e2e/**'), joinPath(c.path, '**/*.{test,spec}.*')]);
  const roles = [
    { role: 'spec-reviewer', writes: [] },
    { role: 'architect', writes: architectWrites(config) },
    ...['frontend-dev', 'backend-dev'].filter((r) => writes.has(r)).map((r) => ({ role: r, writes: [...new Set(writes.get(r))] })),
    { role: 'qa-tester', writes: [...new Set(tests)] },
    { role: 'reviewer', writes: [] },
    { role: 'debugger', writes: [] },
    { role: 'doc-writer', writes: whitelist },
  ];
  return roles;
}

