test('RF-ADP-02 / RF-MRG-02: permissions and hooks are merged into existing settings and removed cleanly', async (t) => {
  const root = FIXTURES.existingConfig(t);
  write(root, {
    '.claude/settings.json': {
      model: 'opus',
      permissions: { allow: ['Bash(npm test:*)'], deny: ['Read(.env)'] },
      hooks: { PreToolUse: [{ matcher: 'Bash', hooks: [{ type: 'command', command: 'echo team-hook' }] }] },
    },
  });
  git(root, 'add', '-A');
  git(root, '-c', 'core.hooksPath=.git/no-hooks', 'commit', '-qm', 'chore: claude settings');
  const before = snapshot(root);
  assert.equal((await run(['init', '--yes', '--mode', 'team'], { cwd: root })).code, 0);
  const s = JSON.parse(read(root, '.claude/settings.json'));
  assert.equal(s.model, 'opus');
  assert.deepEqual(s.permissions.allow, ['Bash(npm test:*)']);
  assert.equal(s.permissions.deny[0], 'Read(.env)');
  assert.ok(s.permissions.deny.includes('Bash(git push:*)'));
  assert.ok(s.permissions.ask.includes('Bash(npm install:*)'));
  assert.equal(s.hooks.PreToolUse[0].hooks[0].command, 'echo team-hook');
  assert.match(s.hooks.PreToolUse[1].hooks[0].command, /hook\.js" PreToolUse$/);
  for (const e of ['PostToolUse', 'UserPromptSubmit', 'SessionStart', 'SessionEnd', 'Stop']) assert.ok(s.hooks[e], e);
  assert.equal((await run(['sync', '--yes'], { cwd: root })).stdout.includes('Nothing to change'), true);
  assert.equal((await run(['remove', '--yes'], { cwd: root })).code, 0);
  assert.deepEqual(snapshot(root), before);
});

test('the generated hook really runs from .harness/scripts (ES modules, any cwd)', async (t) => {
  const root = FIXTURES.frontend(t);
  await run(['init', '--yes'], { cwd: root });
  const settings = JSON.parse(read(root, '.claude/settings.local.json'));
  const command = settings.hooks.PreToolUse.at(-1).hooks[0].command;
  assert.equal(command, 'node "$CLAUDE_PROJECT_DIR/.harness/scripts/hook.js" PreToolUse');
  const payload = JSON.stringify({ session_id: 'x', cwd: root, hook_event_name: 'PreToolUse', tool_name: 'Bash', tool_input: { command: 'git push' } });
  const r = spawnSync(process.execPath, [path.join(root, '.harness/scripts/hook.js'), 'PreToolUse'], { input: payload, encoding: 'utf8', cwd: path.join(root, 'src'), env: { ...process.env, HARNESS_LANG: 'en', CLAUDE_PROJECT_DIR: root } });
  assert.equal(r.status, 2, r.stderr);
  assert.match(r.stderr, /Committing is the user's job/);
  const ok = spawnSync(process.execPath, [path.join(root, '.harness/scripts/hook.js'), 'PreToolUse'], { input: payload.replace('git push', 'git status'), encoding: 'utf8', env: { ...process.env, CLAUDE_PROJECT_DIR: root } });
  assert.equal(ok.status, 0, ok.stderr);
  const sdd = spawnSync(process.execPath, [path.join(root, '.harness/scripts/sdd.js'), 'status'], { encoding: 'utf8', cwd: root, env: { ...process.env, HARNESS_LANG: 'en' } });
  assert.equal(sdd.status, 0, sdd.stderr);
  assert.match(sdd.stdout, /Active spec: —/);
});

