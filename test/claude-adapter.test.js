test('RF-VER-06: CI template on request, only when the scripts are committed', async (t) => {
  const root = FIXTURES.monorepo(t);
  await run(['init', '--yes', '--mode', 'team'], { cwd: root });
  fs.appendFileSync(path.join(root, 'harness.config.yaml'), '');
  const cfg = read(root, 'harness.config.yaml').replace('provider: none', 'provider: github');
  fs.writeFileSync(path.join(root, 'harness.config.yaml'), cfg);
  assert.equal((await run(['sync', '--yes'], { cwd: root })).code, 0);
  const wf = read(root, '.github/workflows/sdd-harness.yml');
  assert.match(wf, /pnpm install --frozen-lockfile/);
  assert.match(wf, /node \.harness\/scripts\/checks\.js ci --range/);
  assert.match(wf, /sdd\.js verify --component api\n {6}- run: node \.harness\/scripts\/sdd\.js verify --component web/);
  const local = FIXTURES.frontend(t);
  await run(['init', '--yes'], { cwd: local });
  fs.writeFileSync(path.join(local, 'harness.config.yaml'), read(local, 'harness.config.yaml').replace('provider: none', 'provider: github'));
  const r = await run(['sync', '--yes'], { cwd: local });
  assert.match(r.stdout, /CI template needs the harness scripts in the repository/);
});

