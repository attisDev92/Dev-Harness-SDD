test('RF-VER-03/04: the pre-commit hook blocks secrets, stray docs and failing checks; the user can still commit', async (t) => {
  const root = FIXTURES.frontend(t);
  // Quick checks run lint and typecheck: make them real commands for the test.
  // "type": "module" as in many real projects: the extensionless hook must still run (found in the real Claude Code test).
  write(root, { 'package.json': { name: 'shop-web', type: 'module', scripts: { lint: 'node -e "process.exit(require(\'fs\').existsSync(\'lint.fail\') ? 1 : 0)"', test: 'node -e ""' } } });
  git(root, 'add', '-A');
  git(root, 'commit', '-qm', 'chore: scripts');
  assert.equal((await run(['init', '--yes'], { cwd: root })).code, 0);
  assert.equal(git(root, 'config', 'core.hooksPath').trim(), '.harness/githooks');

  const commit = () => spawnSync('git', ['-c', 'user.email=a@b.c', '-c', 'user.name=U', 'commit', '-qm', 'feat: x'], { cwd: root, encoding: 'utf8' });
  // Built at run time so no key-shaped literal lives in the repository.
  write(root, { 'src/config.ts': `export const apiKey = "${'sk-' + 'ant-api03-'}abcdefghijklmnopqrstuvwxyz0123";\n` });
  git(root, 'add', 'src/config.ts');
  let r = commit();
  assert.notEqual(r.status, 0);
  assert.match(r.stderr, /secrets: possible Anthropic key in src\/config\.ts/);

  git(root, 'reset', '-q', 'src/config.ts');
  fs.rmSync(path.join(root, 'src/config.ts'));
  write(root, { 'NOTES.md': '# notes\n', 'src/a.ts': 'export {};\n', 'lint.fail': '' });
  git(root, 'add', 'NOTES.md', 'src/a.ts');
  r = commit();
  assert.match(r.stderr, /docs: NOTES\.md is not in the documentation whitelist/);
  assert.match(r.stderr, /verify: shop-web → npm run lint failed/);

  git(root, 'reset', '-q', 'NOTES.md');
  fs.rmSync(path.join(root, 'lint.fail'));
  r = commit();
  assert.equal(r.status, 0, r.stderr);
});

