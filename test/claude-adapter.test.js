const read = (root, p) => fs.readFileSync(path.join(root, p), 'utf8');
const frontmatter = (text) => Object.fromEntries([...text.matchAll(/^(\w[\w-]*): (.*)$/gm)].map((m) => [m[1], m[2]]));

test('RF-ADP-01 / RF-GEN-04: one subagent per needed role, with its tools and model tier', async (t) => {
  const root = FIXTURES.monorepo(t);
  assert.equal((await run(['init', '--yes'], { cwd: root })).code, 0);
  const agents = fs.readdirSync(path.join(root, '.claude/agents')).sort();
  assert.deepEqual(agents, ['architect.md', 'backend-dev.md', 'debugger.md', 'doc-writer.md', 'frontend-dev.md', 'qa-tester.md', 'reviewer.md', 'spec-reviewer.md']);
  const reviewer = frontmatter(read(root, '.claude/agents/reviewer.md'));
  assert.deepEqual([reviewer.name, reviewer.tools, reviewer.model], ['reviewer', 'Read, Grep, Glob, Bash', 'opus']);
  assert.equal(frontmatter(read(root, '.claude/agents/doc-writer.md')).model, 'haiku');
  assert.equal(frontmatter(read(root, '.claude/agents/frontend-dev.md')).model, 'sonnet');
  // RF-DOM-02: read-only roles cannot edit.
  for (const role of ['spec-reviewer', 'reviewer', 'debugger']) assert.doesNotMatch(frontmatter(read(root, `.claude/agents/${role}.md`)).tools, /Write|Edit/);
  assert.match(read(root, '.claude/agents/frontend-dev.md'), /You may write only in: `apps\/web\/\*\*`/);

  const front = FIXTURES.frontend(t);
  await run(['init', '--yes'], { cwd: front });
  assert.ok(!fs.existsSync(path.join(front, '.claude/agents/backend-dev.md')));
});

