test('edge case 7: a damaged block is reported and left alone', async (t) => {
  const root = await activated(t);
  edit(root, 'AGENTS.md', (s) => s.replace('<!-- harness:end -->', ''));
  const damaged = read(root, 'AGENTS.md');
  edit(root, 'harness.config.yaml', (s) => s.replace('manual_test: task', 'manual_test: spec'));
  const r = await run(['sync', '--yes'], { cwd: root });
  assert.equal(r.code, 1);
  assert.match(r.stderr, /AGENTS\.md: the harness block is damaged/);
  assert.equal(read(root, 'AGENTS.md'), damaged);
});

test('edge case 8: a missing or corrupt manifest is rebuilt from the expected output', async (t) => {
  const root = await activated(t);
  const manifest = read(root, '.harness/manifest.lock');
  fs.rmSync(file(root, '.harness/manifest.lock'));
  let r = await run(['sync', '--yes'], { cwd: root });
  assert.equal(r.code, 0, r.stderr);
  assert.match(r.stdout, /manifest is missing: it will be rebuilt/);
  assert.equal(JSON.parse(read(root, '.harness/manifest.lock')).entries.length, JSON.parse(manifest).entries.length);
  fs.writeFileSync(file(root, '.harness/manifest.lock'), '{ broken');
  r = await run(['sync', '--yes'], { cwd: root });
  assert.match(r.stdout, /manifest is damaged/);
  assert.equal(JSON.parse(read(root, '.harness/manifest.lock')).version, 1);
});

test('edge case 24: changing the mode with hand-edited files asks for each one', async (t) => {
  const root = await activated(t);
  edit(root, 'CLAUDE.local.md', (s) => s.replace('@AGENTS.md', '@AGENTS.md\n@docs/extra.md'));
  edit(root, 'harness.config.yaml', (s) => s.replace('install_mode: local', 'install_mode: team'));
  const r = await run(['sync', '--yes'], { cwd: root });
  assert.equal(r.code, 0, r.stderr);
  assert.match(r.stdout, /CLAUDE\.local\.md is no longer needed but was modified by hand\. → keep my version/);
  assert.match(read(root, 'CLAUDE.local.md'), /docs\/extra\.md/);
});

test('RF-UPG-02 / edge case 25: version differences are reported, nothing is upgraded', async (t) => {
  const root = await activated(t);
  edit(root, 'harness.config.yaml', (s) => s.replace(/harness_version: .*/, 'harness_version: 9.0.0'));
  let r = await run(['sync', '--yes'], { cwd: root });
  assert.match(r.stderr, /uses harness 9\.0\.0, newer than this CLI/);
  assert.match(read(root, 'harness.config.yaml'), /harness_version: 9\.0\.0/);
  edit(root, 'harness.config.yaml', (s) => s.replace(/harness_version: .*/, 'harness_version: 0.0.1'));
  r = await run(['sync', '--yes'], { cwd: root });
  assert.match(r.stderr, /activated with harness 0\.0\.1.*harness upgrade/);
  assert.match(read(root, 'harness.config.yaml'), /harness_version: 0\.0\.1/);
});

test('sync from a subdirectory works on the project root; outside a project it fails', async (t) => {
  const root = await activated(t);
  const r = await run(['sync', '--yes'], { cwd: path.join(root, 'apps', 'web') });
  assert.equal(r.code, 0, r.stderr);
  const plain = FIXTURES.frontend(t);
  const r2 = await run(['sync'], { cwd: plain });
  assert.equal(r2.code, 1);
  assert.match(r2.stderr, /not activated/);
});

test('edge case 26: sync waits for a running agent session or cancels', async (t) => {
  const root = await activated(t);
  const { touchLock, releaseLock } = await import('../src/guards/state.js');
  touchLock(root, 'agent-session');
  const r = await run(['sync', '--yes'], { cwd: root });
  assert.equal(r.code, 1);
  assert.match(r.stderr, /An agent session \(agent-session\) is running tasks/);
  const declined = await run(['sync'], { cwd: root, answers: { waitLock: false } });
  assert.equal(declined.code, 1);

  const { main } = await import('../src/cli/main.js');
  const { createScriptedPrompter } = await import('../src/cli/prompt.js');
  let stdout = '';
  setTimeout(() => releaseLock(root, 'agent-session'), 150);
  const code = await main(['sync'], {
    stdout: { write: (s) => { stdout += s; } }, stderr: { write() {} }, env: { HARNESS_LANG: 'en' }, cwd: root,
    readStdin: async () => '', prompter: createScriptedPrompter({ waitLock: true, apply: true }), lockPollMs: 20,
  });
  assert.equal(code, 0, stdout);
  assert.match(stdout, /Nothing to change/);
});
