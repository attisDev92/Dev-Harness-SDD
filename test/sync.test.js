// harness sync (RF-GEN-09..13, RF-MOD-06, RF-UPG-02, edge cases 7, 8, 24, 25).
import { test } from 'node:test';
import assert from 'node:assert/strict';
import * as fs from 'node:fs';
import path from 'node:path';
import { FIXTURES, run, snapshot, git } from './fixtures.js';

const file = (root, p) => path.join(root, p);
const read = (root, p) => fs.readFileSync(file(root, p), 'utf8');
const edit = (root, p, fn) => fs.writeFileSync(file(root, p), fn(read(root, p)));

async function activated(t, fixture = 'monorepo', args = []) {
  const root = FIXTURES[fixture](t);
  const r = await run(['init', '--yes', ...args], { cwd: root });
  assert.equal(r.code, 0, r.stderr);
  return root;
}

test('RF-GEN-13: two syncs in a row change nothing, byte for byte', async (t) => {
  const root = await activated(t);
  const before = snapshot(root);
  for (let i = 0; i < 2; i += 1) {
    const r = await run(['sync', '--yes'], { cwd: root });
    assert.equal(r.code, 0, r.stderr);
    assert.match(r.stdout, /Nothing to change/);
  }
  assert.deepEqual(snapshot(root), before);
});

test('RF-GEN-09: a config change is shown as a diff before it is applied', async (t) => {
  const root = await activated(t);
  edit(root, 'harness.config.yaml', (s) => s.replace('manual_test: task', 'manual_test: story'));
  const declined = await run(['sync'], { cwd: root, answers: { apply: false } });
  assert.equal(declined.code, 1);
  assert.match(declined.stdout, /--- a\/AGENTS\.md\n\+\+\+ b\/AGENTS\.md/);
  // The monorepo fixture documents in Spanish, so the context is in Spanish.
  assert.match(declined.stdout, /-- Tras cada tarea/);
  assert.match(declined.stdout, /\+- Tras cada historia/);
  assert.doesNotMatch(read(root, 'AGENTS.md'), /Tras cada historia/);
  const r = await run(['sync'], { cwd: root, answers: { apply: true } });
  assert.equal(r.code, 0, r.stderr);
  assert.match(read(root, 'AGENTS.md'), /Tras cada historia/);
});

test('RF-GEN-10: sync --dry-run shows the diff and writes nothing', async (t) => {
  const root = await activated(t);
  edit(root, 'harness.config.yaml', (s) => s.replace('in_scope: 2', 'in_scope: 1'));
  const before = snapshot(root);
  const r = await run(['sync', '--dry-run'], { cwd: root });
  assert.equal(r.code, 0, r.stderr);
  assert.match(r.stdout, /\+- Como máximo 1 intentos automáticos/);
  assert.match(r.stdout, /"in_scope": 1/);
  assert.match(r.stdout, /Dry run: nothing was written/);
  assert.deepEqual(snapshot(root), before);
});

test('RF-GEN-11: a hand-edited generated file offers keep, overwrite or diff', async (t) => {
  const root = await activated(t);
  edit(root, '.harness/templates/spec.md', (s) => s + '\nmy notes\n');
  edit(root, 'harness.config.yaml', (s) => s.replace('specs: es', 'specs: en'));

  const kept = await run(['sync', '--yes'], { cwd: root });
  assert.equal(kept.code, 0, kept.stderr);
  assert.match(kept.stdout, /\.harness\/templates\/spec\.md was generated by the harness and then modified by hand\. → keep my version/);
  assert.match(read(root, '.harness/templates/spec.md'), /my notes/);
  assert.match(read(root, '.harness/templates/plan.md'), /Test strategy/);

  const choices = ['diff', 'overwrite'];
  const r = await run(['sync'], { cwd: root, answers: { 'conflict:.harness/templates/spec.md': () => choices.shift(), apply: true } });
  assert.equal(r.code, 0, r.stderr);
  assert.match(r.stdout, /\n-my notes\n/, 'the diff (mine → harness) was shown');
  assert.doesNotMatch(read(root, '.harness/templates/spec.md'), /my notes/);
  assert.match(read(root, '.harness/templates/spec.md'), /Functional requirements/);
});

test('RF-GEN-12: sync refuses an invalid configuration', async (t) => {
  const root = await activated(t);
  edit(root, 'harness.config.yaml', (s) => s.replace('install_mode: local', 'install_mode: shared'));
  const before = snapshot(root);
  const r = await run(['sync', '--yes'], { cwd: root });
  assert.equal(r.code, 1);
  assert.match(r.stderr, /harness\.config\.yaml:\d+:\d+ {2}install_mode: "shared" is not allowed/);
  assert.deepEqual(snapshot(root), before);
});

test('RF-MOD-06: switching local → team → local migrates the files', async (t) => {
  const root = await activated(t);
  edit(root, 'harness.config.yaml', (s) => s.replace('install_mode: local', 'install_mode: team'));
  let r = await run(['sync', '--yes'], { cwd: root });
  assert.equal(r.code, 0, r.stderr);
  assert.ok(fs.existsSync(file(root, 'CLAUDE.md')));
  assert.ok(!fs.existsSync(file(root, 'CLAUDE.local.md')));
  assert.ok(fs.existsSync(file(root, '.harness/.gitignore')));
  // Artifacts stay local (the init default in local mode), so only they remain excluded.
  assert.doesNotMatch(read(root, '.git/info/exclude'), /\/\.harness\//);
  assert.match(read(root, '.git/info/exclude'), /\/specs\//);
  assert.match(git(root, 'status', '--porcelain'), /\?\? \.harness\//);

  edit(root, 'harness.config.yaml', (s) => s.replace('install_mode: team', 'install_mode: local'));
  r = await run(['sync', '--yes'], { cwd: root });
  assert.equal(r.code, 0, r.stderr);
  assert.ok(!fs.existsSync(file(root, 'CLAUDE.md')));
  assert.ok(fs.existsSync(file(root, 'CLAUDE.local.md')));
  assert.equal(git(root, 'status', '--porcelain'), '');
});

